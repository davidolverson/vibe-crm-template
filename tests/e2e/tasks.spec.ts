/**
 * Tasks CRUD - E2E tests
 *
 * Covers:
 *   - Adding a task via the "Add Task" dialog
 *   - Newly created task appears in the task list
 *   - Completing a task via the "Complete" button toggles its status badge
 *   - Overdue tab shows tasks whose due date is in the past
 *
 * Uses timestamp-based unique titles to avoid collisions across runs.
 */

import { test, expect } from './fixtures';

const RUN_ID = `e2e-${Date.now()}`;

function taskTitle(label: string) {
  return `${label} ${RUN_ID}`;
}

/** Returns an ISO date string N days from now (negative = past). */
function relativeDate(offsetDays: number): string {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10); // YYYY-MM-DD
}

test.describe('Tasks', () => {
  test.beforeEach(async ({ loggedInPage }) => {
    await loggedInPage.goto('/tasks');
    await loggedInPage.waitForLoadState('networkidle');
  });

  // ---------------------------------------------------------------------------
  // Render
  // ---------------------------------------------------------------------------

  test('tasks page loads with the tab bar visible', async ({
    loggedInPage: page,
  }) => {
    // Tabs: All, Pending, Completed, Overdue
    await expect(page.getByRole('tab', { name: /all/i })).toBeVisible();
    await expect(page.getByRole('tab', { name: /pending/i })).toBeVisible();
    await expect(page.getByRole('tab', { name: /completed/i })).toBeVisible();
    await expect(page.getByRole('tab', { name: /overdue/i })).toBeVisible();
  });

  test('"Add Task" button is visible', async ({ loggedInPage: page }) => {
    await expect(page.getByRole('button', { name: /add task/i })).toBeVisible();
  });

  // ---------------------------------------------------------------------------
  // Create
  // ---------------------------------------------------------------------------

  test('add task dialog opens when "Add Task" is clicked', async ({
    loggedInPage: page,
  }) => {
    await page.getByRole('button', { name: /add task/i }).click();

    await expect(page.getByRole('dialog')).toBeVisible({ timeout: 8_000 });
    await expect(page.getByRole('heading', { name: /new task/i })).toBeVisible();
  });

  test('task form contains title, description, priority, due date fields', async ({
    loggedInPage: page,
  }) => {
    await page.getByRole('button', { name: /add task/i }).click();
    await expect(page.getByRole('dialog')).toBeVisible();

    await expect(page.getByLabel(/title/i)).toBeVisible();
    await expect(page.getByLabel(/description/i)).toBeVisible();
    await expect(page.getByLabel(/priority/i)).toBeVisible();
    await expect(page.getByLabel(/due date/i)).toBeVisible();
    await expect(page.getByRole('button', { name: /create task/i })).toBeVisible();
  });

  test('submitting the add-task form creates the task', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Write unit tests');

    await page.getByRole('button', { name: /add task/i }).click();
    await expect(page.getByRole('dialog')).toBeVisible({ timeout: 8_000 });

    await page.fill('#title', title);
    await page.fill('#description', 'Auto-generated by Playwright e2e suite');

    await page.getByRole('button', { name: /create task/i }).click();

    // Dialog closes on success
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });
  });

  // ---------------------------------------------------------------------------
  // Read - list
  // ---------------------------------------------------------------------------

  test('created task appears in the task list', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Review PR feedback');

    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // The title should appear in the list on the "All" tab (which is default)
    await expect(page.getByText(title)).toBeVisible({ timeout: 10_000 });
  });

  test('created task shows "pending" status badge', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Deploy to staging');

    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // Find the task row and check its status badge
    const taskRow = page.locator('li').filter({ hasText: title });
    await expect(taskRow).toBeVisible({ timeout: 10_000 });
    await expect(taskRow.getByText('pending')).toBeVisible();
  });

  // ---------------------------------------------------------------------------
  // Complete / toggle
  // ---------------------------------------------------------------------------

  test('clicking "Complete" on a task changes its status badge to "completed"', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Fix login bug');

    // Create the task
    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // Locate the row and click the "Complete" button
    const taskRow = page.locator('li').filter({ hasText: title });
    await expect(taskRow).toBeVisible({ timeout: 10_000 });

    const completeBtn = taskRow.getByRole('button', { name: /complete/i });
    await expect(completeBtn).toBeVisible();
    await completeBtn.click();

    // Status badge should update to "completed" - the server action is
    // optimistic-updated in the client component so we expect a quick change.
    await expect(taskRow.getByText('completed')).toBeVisible({ timeout: 10_000 });
  });

  test('completed task can be reopened with the "Reopen" button', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Update docs');

    // Create and immediately complete it
    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    const taskRow = page.locator('li').filter({ hasText: title });
    await taskRow.getByRole('button', { name: /complete/i }).click();
    await expect(taskRow.getByText('completed')).toBeVisible({ timeout: 10_000 });

    // Reopen
    const reopenBtn = taskRow.getByRole('button', { name: /reopen/i });
    await expect(reopenBtn).toBeVisible({ timeout: 5_000 });
    await reopenBtn.click();

    // Should flip back to pending
    await expect(taskRow.getByText('pending')).toBeVisible({ timeout: 10_000 });
  });

  // ---------------------------------------------------------------------------
  // Overdue tab
  // ---------------------------------------------------------------------------

  test('overdue tab shows tasks that are past their due date', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Overdue task check');
    const yesterday = relativeDate(-1);

    // Create a task due yesterday
    await page.getByRole('button', { name: /add task/i }).click();
    await expect(page.getByRole('dialog')).toBeVisible({ timeout: 8_000 });
    await page.fill('#title', title);
    await page.fill('#dueDate', yesterday);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // Switch to the Overdue tab
    await page.getByRole('tab', { name: /overdue/i }).click();

    // Our task should appear there
    await expect(page.getByText(title)).toBeVisible({ timeout: 10_000 });
  });

  test('overdue tab does NOT show tasks with a future due date', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Future task not overdue');
    const tomorrow = relativeDate(7);

    // Create a task due in the future
    await page.getByRole('button', { name: /add task/i }).click();
    await expect(page.getByRole('dialog')).toBeVisible({ timeout: 8_000 });
    await page.fill('#title', title);
    await page.fill('#dueDate', tomorrow);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // Switch to Overdue tab
    await page.getByRole('tab', { name: /overdue/i }).click();

    // This specific task should NOT be there
    await expect(page.getByText(title)).not.toBeVisible({ timeout: 5_000 });
  });

  // ---------------------------------------------------------------------------
  // Completed tab
  // ---------------------------------------------------------------------------

  test('completed tab shows tasks after they are marked complete', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Task for completed tab');

    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    // Complete from the All tab
    const taskRow = page.locator('li').filter({ hasText: title });
    await taskRow.getByRole('button', { name: /complete/i }).click();
    await expect(taskRow.getByText('completed')).toBeVisible({ timeout: 10_000 });

    // Now check the Completed tab
    await page.getByRole('tab', { name: /completed/i }).click();
    await expect(page.getByText(title)).toBeVisible({ timeout: 10_000 });
  });

  // ---------------------------------------------------------------------------
  // Delete
  // ---------------------------------------------------------------------------

  test('deleting a task removes it from the list', async ({
    loggedInPage: page,
  }) => {
    const title = taskTitle('Task to delete');

    await page.getByRole('button', { name: /add task/i }).click();
    await page.fill('#title', title);
    await page.getByRole('button', { name: /create task/i }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 10_000 });

    const taskRow = page.locator('li').filter({ hasText: title });
    await expect(taskRow).toBeVisible({ timeout: 10_000 });

    // Click the trash icon (aria-label="Delete task")
    await taskRow.getByRole('button', { name: /delete task/i }).click();

    // Task should disappear from the list
    await expect(page.getByText(title)).not.toBeVisible({ timeout: 10_000 });
  });
});
